package org.openfsp.simulator

enum class Scenario {
    SUCCESS,
    DECLINE,
    INSUFFICIENT,
    TIMEOUT,
    TIMEOUT_THEN_SUCCESS,
    TIMEOUT_THEN_NOTHING,
    PENDING_FOREVER,
    EXPIRE,
    NO_CALLBACK,
    DUPLICATE_CALLBACK,
    LATE_CALLBACK,
    UNKNOWN_STATUS,
    CREDENTIAL_ECHO,
    CONTRADICT,
    PROVIDER_ERROR,
    AMOUNT_MISMATCH,
}

enum class Outcome(
    val wire: String,
) {
    SUCCESSFUL("SUCCESSFUL"),
    FAILED("FAILED"),
    EXPIRED("EXPIRED"),
}
